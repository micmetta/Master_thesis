"use client"; // to specify that this file will be executed on the client-side in the next.js app

import React, { useState, useEffect, useRef, useCallback} from 'react';
import { handleButtonClick } from '@/lib/page/actionsPage/handleButtonClick';
import "./table.css";


export default function Home() {

  // - Declaration of states, each state is a pair made like this:
  //    (value of the current state, function to update the state and force re-rendering of the component)
  const [nlQuery, setNlQuery] = useState<string>('');  // state to store query NL (initialised with empty string)
  const [sqlQuery, setSqlQuery] = useState<string>(''); // state to store the SQL query generated by the backend
  const [columnNames, setColumnNames] = useState<string[]>([]); // state for column names
  const [queryResults, setQueryResults] = useState<string[][]>([]); // state for result tuples (queryResults will contain the resultest tuples returned by the backend)
  const [displayedResults, setDisplayedResults] = useState<string[][]>([]); // state for the results shown (groups of 100)
  const [loading, setLoading] = useState<boolean>(false); // loading status during inference required
  const [error, setError] = useState<string | null>(null); // state for the error
  const [unavailabilityNode, setUnavailabilityNode] = useState<string | null>(null); // state to inform the user of the momentary unavailability of a requested inference execution node
  const [page, setPage] = useState<number>(1); // state for the number of loaded pages
  const [responseTime, setResponseTime] = useState<number | null>(null); // state to calculate the response time
  const RESULTS_PER_PAGE = 100; // number of the results per page
  const tableContainerRef = useRef<HTMLDivElement>(null); // reference for the scrollable table container used for loading multiple results when the user scrolls
  const [model, setModel] = useState<string>('8B'); // state that stores the user-selected model choice (Default: model 8B)  
  const [tooltipText, setTooltipText] = useState<string>(''); // state for tooltip text
  
  // I define the 'handleButtonClickWrapper' (compatible with 'onClick') which internally invokes the 'handleButtonClick' that will handle the request.
  const handleButtonClickWrapper = async () => {
    await handleButtonClick(
        nlQuery,
        model,
        setLoading,
        setError,
        setSqlQuery,
        setColumnNames,
        setQueryResults,
        RESULTS_PER_PAGE,
        setDisplayedResults,
        setPage,
        setResponseTime,
        setUnavailabilityNode
    );
  };


  // Auxiliary function to 'useEffect()' below.
  const loadMoreResults = useCallback(() => {
    const nextPage = page + 1;
    const startIndex = (nextPage - 1) * RESULTS_PER_PAGE;
    const endIndex = startIndex + RESULTS_PER_PAGE;
    const moreResults = queryResults.slice(startIndex, endIndex);

    setDisplayedResults(prev => [...prev, ...moreResults]);
    setPage(nextPage); // update total number of pages
  }, [page, RESULTS_PER_PAGE, queryResults]);
  
  // Special function to activate the loading of more results as the user scrolls to the bottom of the table (Lazy loading).
  useEffect(() => {
    const handleScroll = () => {
      const container = tableContainerRef.current; // I take the table reference
      if (container) {
        if (container.scrollHeight - container.scrollTop <= container.clientHeight + 10) {
          if (!loading && displayedResults.length < queryResults.length) { // the update will only be requested if there is no upload already and there are still tuples to be displayed
            loadMoreResults();
          }
        }
      }
    };
    const container = tableContainerRef.current;
    if (container) {
      container.addEventListener('scroll', handleScroll); // I add a listener to the scroll event of the table container (whenever there is scrolling on the table, the 'handleScroll' function will be executed)
    }
    return () => {
      if (container) {
        container.removeEventListener('scroll', handleScroll); // remove the listener when the table container is removed from the DOM
      }
    };
  }, [displayedResults, queryResults, loading, loadMoreResults]); // the function 'useEffect' will be executed whenever the values of 'displayedResults', 'queryResult' or 'loading' change.
  

  
  return (
    <div>
      {/* Main page title */}
      <h1 style={{ textAlign: 'center', marginTop: '40px', fontWeight: 'bold', fontSize: '36px' }}>
        SQL Query Generator
      </h1>

      {/* Sub-section */}
      <p style={{ textAlign: 'center', marginBottom: '30px', marginTop: '20px', fontWeight: 'bold', fontSize: '17px', lineHeight: '1.5'}}>
      First select the model to be used during inference, then write the query in natural language (English/Italian) and finally click on the button to generate the SQL query and obtain the results.
      </p>

      <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', minHeight: '20vh' }}>

        {/*  Model selector */}
        <label htmlFor="modelSelect" style={{ marginBottom: '10px', fontWeight: 'bold', fontSize: '17px' }}>Choose LLM model:</label>
        
        <div style={{ position: 'relative', display: 'inline-block' }}>
        <select
          id="modelSelect"
          value={model}
          onChange={(e) => setModel(e.target.value)}
          onMouseOver={(e) => {
            const target = e.target as HTMLSelectElement; // cast to HTMLSelectElement
            if (target.value === '8B') {
              setTooltipText("Lower accuracy (92%-English, 89%-Italian) - Lower average waiting time (30 seconds)");
            } else {
              setTooltipText("Higher accuracy (96%-English, 93%-Italian) - Longer average waiting time (70 seconds)");
            }
          }}
          onMouseOut={() => setTooltipText('')} // I hide the tooltip when the mouse exits
          style={{
            padding: '5px',
            fontSize: '16px',
            marginBottom: '20px',
            border: '2px solid #ccc',
            borderRadius: '8px',
            transition: 'border-color 0.3s ease, box-shadow 0.3s ease',
            outline: 'none',
            height: '40px',
            width: 'auto',
          }}
          onFocus={(e) => {
            e.target.style.borderColor = '#007BFF';
            e.target.style.boxShadow = '0px 4px 12px rgba(0, 123, 255, 0.4)';
          }}
          onBlur={(e) => {
            e.target.style.borderColor = '#ccc';  // returns to the original border colour
            e.target.style.boxShadow = 'none';  // returns without shading
          }}
        >
          <option value="8B">Model 8B</option>
          <option value="70B">Model 70B</option>
        </select>

          {/* dynamic Tooltip */}
          {tooltipText && (
            <div
              style={{
                position: 'absolute',
                top: '0%', // centre the tooltip vertically with respect to the selector
                left: '105%', // I move the tooltip to the right of the selector
                backgroundColor: '#333',
                color: '#fff',
                padding: '5px 10px',
                borderRadius: '5px',
                marginTop: '5px',
                fontSize: '14px',
                whiteSpace: 'nowrap',
                zIndex: 1
              }}
            >
              {tooltipText}
            </div>
          )}
        </div>

        {/* TextArea */}
        <textarea
          value={nlQuery}
          onChange={(e) => setNlQuery(e.target.value)}
          placeholder="Inserisci query in linguaggio naturale"
          style={{
            padding: '12px',
            width: '450px',
            height: '160px',
            border: '2px solid #ccc',
            borderRadius: '15px',
            resize: 'none', // prevent vertical resizing by the user
            boxShadow: '0px 4px 10px rgba(0, 0, 0, 0.1)',
            fontSize: '16px',
            transition: 'border-color 0.3s ease, box-shadow 0.3s ease',
            outline: 'none'
          }}
          onFocus={(e) => {
            e.target.style.borderColor = '#007BFF';  // light blue border colour when the textarea is clicked (visual feedback)
            e.target.style.boxShadow = '0px 4px 12px rgba(0, 123, 255, 0.4)'; // accentuated shading at the click of the textarea (visual feedback)
          }}
          onBlur={(e) => {
            e.target.style.borderColor = '#ccc';  // returns to the original border colour
            e.target.style.boxShadow = '0px 4px 10px rgba(0, 0, 0, 0.1)'; // returns with light shading
          }}
        />
        {/* Custom Button - 'Generate SQL' */}
        <button
          onClick={handleButtonClickWrapper}
          disabled={loading} // the button will be disabled until the loading finishes
          style={{
            padding: '10px 20px',
            marginTop: '10px',
            backgroundColor: loading ? '#999' : '#E19243',
            color: 'white',
            border: 'none',
            borderRadius: '5px',
            cursor: 'pointer',
            fontSize: '16px',
            transition: 'background-color 0.3s ease',
          }}
          onMouseOver={(e) => !loading && (e.currentTarget.style.backgroundColor = '#C87A39')}
          onMouseOut={(e) => !loading && (e.currentTarget.style.backgroundColor = "#E19243")}
        >
          Generate SQL
        </button>

        {loading && (
          <>
            <div className="spinner" style={{
              width: '24px',
              height: '24px',
              border: '4px solid #f3f3f3',
              borderTop: '4px solid #3498db',
              borderRadius: '50%',
              animation: 'spin 1s linear infinite', // circular animation
              marginTop: '20px'
            }}></div>
            <p>Loading request..</p>
          </>
        )}

        {/* if an error occurs, it will be displayed in red immediately below the button */}
        {error && (
          <p style={{
            color: 'red',
            whiteSpace: 'pre-wrap',  // handles new lines and spaces better
            wordWrap: 'break-word',  // allows the text to wrap without straining to stay on a single line
            maxWidth: '100%'  // ensures that the container is not limited in width
          }}>
            {error}
          </p>
        )}

        {/* if an excessive waiting time occurs, this warning for the user will be displayed in blue immediately below the button */}
        {unavailabilityNode && (
          <p style={{
            color: 'blue',
            whiteSpace: 'pre-wrap',
            wordWrap: 'break-word',
            maxWidth: '100%'
          }}>
            {unavailabilityNode}
          </p>
        )}
      
      </div>
      
      {sqlQuery && (
        <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', marginTop: '20px' }}>
          <h3 style={{ fontWeight: 'bold' }}>SQL query generated:</h3>
          <pre style={{ textAlign: 'center', whiteSpace: 'pre-wrap', wordWrap: 'break-word' }}>
            {sqlQuery}
          </pre>

          {responseTime !== null && (
            <>
              <h3 style={{ fontWeight: 'bold', marginTop: '20px' }}>Time taken for response:</h3>
              <pre style={{ textAlign: 'center', whiteSpace: 'pre-wrap', wordWrap: 'break-word' }}>
                {responseTime.toFixed(2)} seconds
              </pre>
            </>
          )}
        </div>
      )}

      {columnNames.length > 0 && displayedResults.length > 0 && (
        <div style={{ marginTop: '10px', maxWidth: '100%' }}>
          <h3 style={{ fontWeight: 'bold', marginBottom: '10px' }}>
            Query Results (Displayed {displayedResults.length} of {queryResults.length} results):
          </h3>
          {/* Scrollable table container */}
          <div
            ref={tableContainerRef}
            style={{
              maxHeight: '450px',
              overflowY: 'scroll',
              overflowX: 'auto',
              border: '1px solid #ccc',
            }}
          >
            <table className='table'>
              <thead> {/* table header */}
                <tr> 
                  {/* subsequent header columns (column names) */}
                  {columnNames.map((col, index) => (
                    <th key={index}
                      style={{
                        position: 'sticky',
                        top: 0,
                        zIndex: 1,
                        border: '1px solid black',
                        padding: '10px',
                        fontWeight: 'bold',
                      }}
                    >
                      {col}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody> {/* body table */}
                {/* with '.map' I iterate over the array 'displayedResults', each element will be a row in the table */}
                {/* row: array containing the values of each row in the table (no header row) */}
                {/* rowIndex: unique incremental row index generated by the map (starts from 0) */}
                {displayedResults.map((row, rowIndex) => (
                  <tr key={rowIndex}> {/* per ogni nuova riga creo un nuovo <tr> */}
                    
                    {/* I iterate again on 'row' to obtain the individual values (cells) of each row */}
                    {row.map((cell, cellIndex) => (
                      <td key={cellIndex}> {/* property in React server to uniquely identify each cell within the row and optimise DOM management */}
                        {cell !== null ? cell.toString() : 'NULL'} {/* if the value of the current cell is null then I display the string 'NULL' otherwise I convert the value to a string */}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
}