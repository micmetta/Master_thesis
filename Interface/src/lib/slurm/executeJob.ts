import { exec } from 'child_process';
import { addJob, getJob, updateJobCanRemoved} from '../sharedDictionaryJobs/dictJobs.mjs';

const MAX_RETRY_ATTEMPTS = 3; // Maximum number of attempts
const RETRY_DELAY = 10000; // Delay between attempts (10 seconds)
const WAITJOBSTATUS = 1000; // Waiting time for job polling

// Function to execute an SSH command with reconnection attempts
async function executeWithRetries(command: string, maxRetries: number, delay: number, userId: string, selectedModel: string): Promise<string> {
  let attempts = 0;

  return new Promise((resolve, reject) => {
    const tryExec = () => {
      exec(command, (error, stdout, stderr) => {
        if (error) {
          attempts++;
          console.error(`(slurm/executeJob.ts/executeWithRetries) Error during command execution: ${error.message} - Attempt: ${attempts}`);

          if (attempts < maxRetries) {
            console.log(`(slurm/executeJob.ts/executeWithRetries) I will try again in ${delay / 1000} seconds..`);
            setTimeout(tryExec, delay);
          } else {
            reject(`exceeded the maximum number of connection attempts to SLURM (${maxRetries})`);
          }
        } else if (stderr) {
          console.error(`(slurm/executeJob.ts/executeWithRetries) Error (stderr): ${stderr}`);
          reject(stderr);
        } else {
          console.log(`\n\n(slurm/executeJob.ts/executeWithRetries) Successful connection to SLURM for the user: ${userId} - Model selected: ${selectedModel}\n`);
          resolve(stdout); // success
        }
      });
    };
    tryExec();
  });
}

// Function for monitoring job completion
async function checkJobCompletion(jobId: string): Promise<string | null> {
  return new Promise((resolve) => {
    const pollJobStatus = async () => {
      const jobIsCompleted = await getJob(jobId);
      switch (jobIsCompleted.status) {
        case 'running':
          break; // the job is still running so I do not resolve the promise to allow 'pollJobStatus()' to continue monitoring the job
        case 'completed':
          resolve(jobIsCompleted.result); // the job was completed and then I return the querySQL that was generated by the model
          return;
        case 'cancelled-by-slurm':
          resolve('cancelled-by-slurm');
          return;
        default:
          resolve('cancelled-timeout');
          return;
        }
      setTimeout(pollJobStatus, WAITJOBSTATUS); // wait 'WAITJOBSTATUS' seconds before re-executing 'pollJobStatus()'.
    };

    pollJobStatus(); // call
  });
}

// Main function to execute a job request on SLURM and monitor its status
export async function executeJobWithStatus(command: string, question: string, userId: string, selectedModel: string): Promise<{ userId: string, output: string } | { error: string }> {
  if (!command || !question || !userId || !selectedModel) {
    throw new Error('Missing command, application, userId or model');
  }
  
  let sshCommand = ""
  if(selectedModel=="8B"){
    sshCommand = `ssh ${process.env.NEXT_PUBLIC_SSH_USER}@${process.env.NEXT_PUBLIC_SSH_SERVER} "cd ${process.env.NEXT_PUBLIC_PATH_FILE_INFERENCES} && sbatch ${command} \\"${question}\\" \\"${userId}\\" \\"${process.env.PATH_BASE_MODEL_REMOTE_FOR_INFERENCE_8B_SCRIPT}\\" \\"${process.env.PATH_MODEL_USE_REMOTE_FOR_INFERENCE_8B_SCRIPT}\\" \\"${process.env.EXPORT_PYTHON_PATH}\\""`;
  }else{
    sshCommand = `ssh ${process.env.NEXT_PUBLIC_SSH_USER}@${process.env.NEXT_PUBLIC_SSH_SERVER} "cd ${process.env.NEXT_PUBLIC_PATH_FILE_INFERENCES} && sbatch ${command} \\"${question}\\" \\"${userId}\\" \\"${process.env.PATH_BASE_MODEL_REMOTE_FOR_INFERENCE_70B_SCRIPT}\\" \\"${process.env.PATH_MODEL_USE_REMOTE_FOR_INFERENCE_70B_SCRIPT}\\" \\"${process.env.EXPORT_PYTHON_PATH}\\""`;
  }

  let jobIdFinally: string = '';
  try {
    const stdout = await executeWithRetries(sshCommand, MAX_RETRY_ATTEMPTS, RETRY_DELAY, userId, selectedModel);
    const jobIdMatch = stdout.match(/Submitted batch job (\d+)/);
    const jobId: string | null = jobIdMatch ? jobIdMatch[1] : null;

    if (jobId) {
      await addJob(jobId, userId, selectedModel);
      jobIdFinally = jobId;
      const querySQL = await checkJobCompletion(jobId);

      if((querySQL) && (querySQL != 'cancelled-by-slurm') && (querySQL != 'cancelled-timeout')){
        return { userId, output: querySQL };
      } else if(querySQL === 'cancelled-timeout'){
        throw new Error("The job was cancelled for the maximum waiting time. Please try again.");
      } else{
        throw new Error("The job was deleted from SLURM. Wait a few seconds and try again.");
      }
    } else {
      throw new Error("Cannot obtain job ID.");
    }
  } catch (error) {
    throw new Error(`generate in executeJobWithStatus.ts): ${error}`);

  } finally{
    if(jobIdFinally != ''){
      updateJobCanRemoved(jobIdFinally); // warning the pooling of 'jobsManager.mjs' that the job being monitored can be removed from the structure 
    }
  }
}
