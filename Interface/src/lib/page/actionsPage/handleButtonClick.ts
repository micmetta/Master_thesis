import { handleButtonClickServer } from '@/lib/handleInference/handleButtonClickServer';
import { generateUniqueSessionId } from '@/lib/page/utilsPage/helpers';

// Type definition for each callback passed
type SetState<T> = (value: T) => void;
type SetError = (error: string | null) => void;
type SetLoading = (loading: boolean) => void;
type SetResponseTime = (time: number | null) => void;
type SetResults = (results: string[][]) => void;

export async function handleButtonClick(
    nlQuery: string,
    model: string,
    setLoading: SetLoading,
    setError: SetError,
    setSqlQuery: SetState<string>,
    setColumnNames: SetState<string[]>,
    setQueryResults: SetResults,
    RESULTS_PER_PAGE: number,
    setDisplayedResults: SetResults,
    setPage: SetState<number>,
    setResponseTime: SetResponseTime,
    setUnavailabilityNode: SetState<string | null>
) {
    if (nlQuery.trim() === '') {
        alert("ERROR: The text bar cannot be empty.");
        return;
    }

    setLoading(true);
    setError(null);
    setSqlQuery('');
    setColumnNames([]);
    setQueryResults([]);
    setDisplayedResults([]); // (React creates a reference to the empty 'displayedResults' array)
    setPage(1);
    setResponseTime(null);  // reset del timer
    setUnavailabilityNode(null);

    // - With this small piece of code I handle the case where inference times become longer than average (compared to the chosen model)
    //   so that feedback is still shown to the user with a message in blue instead of red:
    const TIMEOUT_THRESHOLD_8B = 40000; // 40s will be the minimum waiting time before notifying the user about system slowdown (if the user has chosen the 8B model)
    const TIMEOUT_THRESHOLD_70B = 100000; // 100s will be the minimum waiting time before notifying the user about system slowdown (if the user has chosen the 70B model)
    const timeoutUnvailableNode = model === '8B' ? TIMEOUT_THRESHOLD_8B : TIMEOUT_THRESHOLD_70B;
    // - I invoke the 'setTimeout()' function which will take care of executing the callback after a certain time equal to 'TIMEOUT_THRESHOLD' to notify the user of the cause 
    //   of any delay in the execution of his request:
    const timer = setTimeout(() => {
      setUnavailabilityNode("The execution time of the request has increased due to the momentary unavailability of a calculation node, please continue to wait so as not to lose priority.");
    }, timeoutUnvailableNode);
    
    // - I send a request to SLURM and await the results
    try {
        const sessionId = generateUniqueSessionId();
        const startTime = performance.now();
        const result = await handleButtonClickServer(nlQuery, sessionId, model);
        const endTime = performance.now();
        setResponseTime((endTime - startTime) / 1000); // time in seconds
        
        if (!result.error) {
            setSqlQuery(result.output);
            setColumnNames(result.columns);
            setQueryResults(result.rows);
            setDisplayedResults(result.rows.slice(0, RESULTS_PER_PAGE));
            if(result.rows.length === 0){
                setError("There is no data in the database that matches with the SQL query generated by the model.");
            }
        }else {
            if(result.output != ''){
            setSqlQuery(result.output);
            }
            setError(result.error);
        }
    } catch (error) {
        setError("An error occurred while sending the request to the server, please try again. " + "(" + error + ")");
    } finally {
        setUnavailabilityNode(null); // cleaning the node unavailability message
        setLoading(false); // end of loading
        clearTimeout(timer); // interrupts the timeout for the unavailability message
    }
}
