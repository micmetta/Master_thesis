import { Mutex } from 'async-mutex';

// Data structure (dictionary) to store and manage active jobs within the application:
// - global is used to share the same dictionary between the different modules that use it. 
// - The dictionary is instantiated as soon as the jobsManager.mjs module is executed.
global.activeJobs = global.activeJobs || {};

// I instantiate the mutex
const mutex = new Mutex();


//////////////////////////// FUNCTIONS FOR MANAGING global.activeJobs with mutex ////////////////////////////

// Function to add a job to the dictionary
async function addJob(jobId, userId, selectedModel) {
  const release = await mutex.acquire();
  try {
    global.activeJobs[jobId] = {
      status: 'running', // possible values during execution: 'running', 'completed', 'cancelled-timeout' or 'cancelled-by-slurm'.
      userId: userId,
      result: null, // querySQL generated by the model
      numControl: 0, // number of checks made to see whether the job is still running or not (which is reset to 0 every few seconds depending on the choice of model)
      numTotalControl: 0, // number of total checks done to see if the job is still running or not (NOT reset to 0) 
                          // and once it reaches a certain value (depending on the model chosen) the job will be directly deleted from SLURM.
                          // This field then allows me to delete the job after it has been queued for some time so that it does not remain in the structure and lead to unnecessary slowdowns in backend management.
      selectedModel: selectedModel, // model requested by user for this job
      canRemoved: false // will only be true when the job can be safely removed from the structure
    };
  } finally {
    release();
  }
}

// Function to obtain all jobs
async function getActiveJobs() {
  const release = await mutex.acquire(); // I acquire the lock before reading
  try {
    return global.activeJobs;
  } finally {
    release(); // I release the lock
  }
}

// Function for obtaining job info
async function getJob(jobId) {
  const release = await mutex.acquire();
  try {
    return global.activeJobs[jobId] || null;
  } finally {
    release();
  }
}

// Function to obtain all keys (ids) of jobs
async function getALLKeysJobs() {
  const release = await mutex.acquire();
  try {
    return Object.keys(global.activeJobs);
  } finally {
    release();
  }
}

// Function to obtain the value of the 'numControl' field of the job
async function getNumControlJob(jobId) {
  const release = await mutex.acquire();
  try {
    return global.activeJobs[jobId].numControl;
  } finally {
    release();
  }
}

// Function to obtain the value of the 'numTotalControl' field of the job
async function getNumTotalControlJob(jobId) {
  const release = await mutex.acquire();
  try {
    return global.activeJobs[jobId].numTotalControl;
  } finally {
    release();
  }
}

// Function to obtain the value of the job's 'selectedModel' field
async function getSelectedModelJob(jobId) {
  const release = await mutex.acquire();
  try {
    return global.activeJobs[jobId].selectedModel;
  } finally {
    release();
  }
}

// Function to update job status
async function updateJobStatus(jobId, status, result) {
  const release = await mutex.acquire();
  try {
    if (global.activeJobs[jobId]) {
      global.activeJobs[jobId].status = status;
      if (result) {
        global.activeJobs[jobId].result = result;
      }
    }
  } finally {
    release();
  }
}

// Function specifying that the job can be removed from the dictionary
async function updateJobCanRemoved(jobId) {
  const release = await mutex.acquire();
  try {
    if (global.activeJobs[jobId]) {
      global.activeJobs[jobId].canRemoved = true;
    }
  } finally {
    release();
  }
}

// Function to increment the 'numControl' value of the job by 1
async function updateIncrementJobNumControl(jobId) {
  const release = await mutex.acquire();
  try {
    if (global.activeJobs[jobId]) {
      global.activeJobs[jobId].numControl += 1;
    }
  } finally {
    release();
  }
}

// Function to reset the job's 'numControl' value to 0
async function updateResetJobNumControl(jobId) {
  const release = await mutex.acquire();
  try {
    if (global.activeJobs[jobId]) {
      global.activeJobs[jobId].numControl = 0;
    }
  } finally {
    release();
  }
}

// Function to increment the value of 'numTotalControl' of the job by 1
async function updateIncrementJobNumTotalControl(jobId) {
  const release = await mutex.acquire();
  try {
    if (global.activeJobs[jobId]) {
      global.activeJobs[jobId].numTotalControl += 1;
    }
  } finally {
    release();
  }
}

// Function to remove a job
async function removeJob(jobId) {
  const release = await mutex.acquire();
  try {
    delete global.activeJobs[jobId];
  } finally {
    release();
  }
}

// Function that deletes a job from the structure
async function deleteALLCompletedORCancelledJobs(){
  const jobIds = await getALLKeysJobs();
  for (const jobId of jobIds){
    const current_job = await getJob(jobId); 
    if(current_job.canRemoved){
      await removeJob(jobId); // I remove the completed job from the jobs structure
      console.log(`(jobManager.js)-(deleteALLCompletedJobs) I deleted the job with id: ${jobId}\n`);
    }
  }
}


// Export the following functions
export {
    addJob,
    getActiveJobs,
    getJob,
    getALLKeysJobs,
    getNumControlJob,
    getNumTotalControlJob,
    getSelectedModelJob,
    updateJobStatus,
    updateJobCanRemoved,
    updateIncrementJobNumControl,
    updateResetJobNumControl,
    updateIncrementJobNumTotalControl,
    deleteALLCompletedORCancelledJobs
};